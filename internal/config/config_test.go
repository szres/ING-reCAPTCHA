func TestLoad_ParsesOverrides(t *testing.T) {
	t.Setenv("TELEGRAM_BOT_TOKEN", "token")
	t.Setenv("DATABASE_PATH", "/tmp/bot.db")
	t.Setenv("IMAGE_CACHE_PATH", "/tmp/images")
	t.Setenv("VERIFY_IMAGE_COUNT", "5")
	t.Setenv("VERIFY_REQUIRED_CORRECT", "4")
	t.Setenv("VERIFY_TIMEOUT_SECONDS", "30")
	t.Setenv("VERIFY_MAX_RETRY", "2")
	t.Setenv("VERIFY_DISTRACTOR_COUNT", "8")
	t.Setenv("REJOIN_COOLDOWN_SECONDS", "60")
	t.Setenv("VERIFY_TEMPBAN_SECONDS", "900")
	t.Setenv("DEFAULT_LANGUAGE", "zh")
	t.Setenv("BOT_ADMIN_IDS", "42, 99, bad, ,123")
	t.Setenv("LEADERBOARD_CHANNEL_ID", "-100123")
	t.Setenv("LEADERBOARD_MESSAGE_ID", "77")
	t.Setenv("DAILY_STATS_TIMEZONE", "UTC")
	t.Setenv("ANTISPAM_BAN_BOT", "SpamBot")
	t.Setenv("VERIFY_SILENT_NOTIFICATIONS", "no")
	t.Setenv("MINIAPP_ENABLED", "yes")
	t.Setenv("MINIAPP_LISTEN_ADDR", "127.0.0.1:9000")
	t.Setenv("MINIAPP_PUBLIC_URL", "https://verify.example///")
	t.Setenv("MINIAPP_SESSION_TTL_SECONDS", "600")
	t.Setenv("EPHEMERAL_FALLBACK_SECONDS", "0")
	t.Setenv("WELCOME_MESSAGE_IN_GROUP", "off")

	cfg := Load()

	assert.Equal(t, "token", cfg.TelegramBotToken)
	assert.Equal(t, "/tmp/bot.db", cfg.DatabasePath)
	assert.Equal(t, "/tmp/images", cfg.ImageCachePath)
	assert.Equal(t, 5, cfg.VerifyImageCount)
	assert.Equal(t, 4, cfg.VerifyRequiredCorrect)
	assert.Equal(t, 30, cfg.VerifyTimeoutSeconds)
	assert.Equal(t, 2, cfg.VerifyMaxRetry)
	assert.Equal(t, 8, cfg.VerifyDistractorCount)
	assert.Equal(t, 60, cfg.RejoinCooldownSeconds)
	assert.Equal(t, 900, cfg.VerifyTempbanSeconds)
	assert.Equal(t, "zh", cfg.DefaultLanguage)
	assert.Equal(t, []int64{42, 99, 123}, cfg.InitialAdminIDs)
	assert.Equal(t, int64(-100123), cfg.LeaderboardChannelID)
	assert.Equal(t, 77, cfg.LeaderboardMessageID)
	assert.Equal(t, "UTC", cfg.DailyStatsTimezone)
	assert.Equal(t, "SpamBot", cfg.AntispamBanBot)
	assert.False(t, cfg.VerifySilentNotifications)
	assert.True(t, cfg.MiniAppEnabled)
	assert.Equal(t, "127.0.0.1:9000", cfg.MiniAppListenAddr)
	assert.Equal(t, "https://verify.example", cfg.MiniAppPublicURL)
	assert.Equal(t, 600, cfg.MiniAppSessionTTLSeconds)
	assert.Equal(t, 0, cfg.EphemeralFallbackSeconds, "0 turns the fallback off")
	assert.False(t, cfg.WelcomeMessageInGroup)
}

func TestEnvHelpers_FallBackOnInvalidValues(t *testing.T) {
	t.Setenv("BAD_INT", "oops")
	t.Setenv("BAD_INT64", "oops")
	t.Setenv("BAD_BOOL", "sometimes")

	assert.Equal(t, 7, getEnvInt("BAD_INT", 7))
	assert.Equal(t, int64(8), getEnvInt64("BAD_INT64", 8))
	assert.True(t, getEnvBool("BAD_BOOL", true))
}
