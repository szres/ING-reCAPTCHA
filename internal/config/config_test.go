	assert.Nil(t, cfg.InitialAdminIDs)
	assert.Equal(t, int64(0), cfg.LeaderboardChannelID)
	assert.Equal(t, 0, cfg.LeaderboardMessageID)
	assert.Equal(t, "Asia/Shanghai", cfg.DailyStatsTimezone)
	assert.Equal(t, "BadBustBot", cfg.AntispamBanBot)
	assert.True(t, cfg.VerifySilentNotifications)
	assert.False(t, cfg.MiniAppEnabled)
	assert.Equal(t, ":8080", cfg.MiniAppListenAddr)
	assert.Equal(t, "", cfg.MiniAppPublicURL)
	assert.Equal(t, 300, cfg.MiniAppSessionTTLSeconds)
	assert.Equal(t, 30, cfg.EphemeralFallbackSeconds)
