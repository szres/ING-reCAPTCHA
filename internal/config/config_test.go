	t.Setenv("MINIAPP_LISTEN_ADDR", "")
	t.Setenv("MINIAPP_PUBLIC_URL", "")
	t.Setenv("MINIAPP_SESSION_TTL_SECONDS", "")
	t.Setenv("EPHEMERAL_FALLBACK_SECONDS", "")
	t.Setenv("WELCOME_MESSAGE_IN_GROUP", "")

	cfg := Load()

	assert.Equal(t, "", cfg.TelegramBotToken)
	assert.Equal(t, "./data/bot.db", cfg.DatabasePath)
